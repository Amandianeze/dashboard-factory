/**
 * Catalog build: docs/lld/*.md front matter → catalog.json, src/spec/generated/panel-kinds.ts and
 * the generated tables in docs/taxonomy.md.
 *
 *   npm run catalog:build            # write outputs
 *   npm run catalog:build -- --check # fail if an output is stale or an item is invalid (verify)
 *
 * catalog.json and panel-kinds.ts are write-protected by .claude/hooks/guard-paths.mjs. In
 * docs/taxonomy.md only the block between the catalog markers is generated; the prose around it
 * is hand-written.
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { parse } from 'yaml';
import {
  ATOMIC_LEVELS,
  BI_LEVELS,
  CatalogItem,
  GAP_PRIORITIES,
  type CatalogItem as Item,
} from './schema';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '../..');
const LLD_DIR = join(ROOT, 'docs/lld');
const TAXONOMY = 'docs/taxonomy.md';
const BEGIN = '<!-- catalog:begin (generated by `npm run catalog:build`; do not edit) -->';
const END = '<!-- catalog:end -->';
const HEADER =
  'Generated by scripts/catalog/build.ts from docs/lld/*.md front matter. Do not edit; run `npm run catalog:build`.';

/* ------------------------------------------------------------------- load */

/** LLD files are every docs/lld/*.md except templates and reports (leading `_` or `gate-`). */
const lldFiles = () =>
  readdirSync(LLD_DIR)
    .filter((f) => f.endsWith('.md') && !f.startsWith('_') && !f.startsWith('gate-'))
    .sort();

export function loadItems(): { items: Item[]; errors: string[] } {
  const items: Item[] = [];
  const errors: string[] = [];
  for (const file of lldFiles()) {
    const text = readFileSync(join(LLD_DIR, file), 'utf8');
    const fm = /^---\n([\s\S]*?)\n---\n/.exec(text)?.[1];
    if (fm === undefined) {
      errors.push(`docs/lld/${file}: no YAML front matter`);
      continue;
    }
    const parsed = CatalogItem.safeParse(parse(fm));
    if (!parsed.success) {
      for (const i of parsed.error.issues)
        errors.push(`docs/lld/${file}: ${i.path.join('.') || '(root)'}: ${i.message}`);
      continue;
    }
    if (`${parsed.data.id}.md` !== file)
      errors.push(`docs/lld/${file}: id "${parsed.data.id}" must match the file name`);
    items.push(parsed.data);
  }
  return { items, errors: [...errors, ...crossChecks(items)] };
}

const levelRank = (i: Item) => ATOMIC_LEVELS.indexOf(i.atomicLevel);

export function crossChecks(items: Item[]): string[] {
  const errors: string[] = [];
  const byId = new Map(items.map((i) => [i.id, i]));
  if (byId.size !== items.length) errors.push('duplicate catalog ids');
  for (const item of items) {
    const at = `docs/lld/${item.id}.md`;
    for (const c of item.composes) {
      const part = byId.get(c);
      if (!part) {
        errors.push(`${at}: composes unknown item "${c}"`);
        continue;
      }
      if (c === item.id) errors.push(`${at}: composes itself`);
      // Frost: build upwards. Organisms may contain organisms; nothing else composes its own level.
      const ok =
        levelRank(part) < levelRank(item) ||
        (item.atomicLevel === 'organism' && part.atomicLevel === 'organism');
      if (!ok)
        errors.push(`${at}: a ${item.atomicLevel} can't compose the ${part.atomicLevel} "${c}"`);
      if (item.status !== 'proposed' && part.status === 'proposed')
        errors.push(`${at}: a ${item.status} item can't be built from the proposed item "${c}"`);
    }
    for (const s of item.source)
      if (!existsSync(join(ROOT, s))) errors.push(`${at}: source file "${s}" does not exist`);
    if (item.replacement && !byId.has(item.replacement))
      errors.push(`${at}: replacement "${item.replacement}" is not a catalog item`);
  }
  return errors;
}

/* ----------------------------------------------------------------- outputs */

const sorted = (items: Item[]) =>
  [...items].sort((a, b) => levelRank(a) - levelRank(b) || a.id.localeCompare(b.id));

/** Kinds a dashboard panel may use: built panel organisms (proposed ones have no renderer yet). */
const panelKinds = (items: Item[]) =>
  sorted(items).filter((i) => i.panel && i.status !== 'proposed');

function buildCatalogJson(items: Item[]): string {
  return JSON.stringify({
    $comment: HEADER,
    version: 1,
    items: sorted(items).map((i) => ({ ...i, lld: `docs/lld/${i.id}.md` })),
  });
}

function buildPanelKindsTs(items: Item[]): string {
  const entries = panelKinds(items).map(
    (i) =>
      `  ${JSON.stringify(i.id)}: { name: ${JSON.stringify(i.name)}, status: ${JSON.stringify(i.status)}, renderers: ${JSON.stringify(i.panel!.renderers)} },`,
  );
  return `/** ${HEADER} */

/** Catalog organisms a dashboard panel can be (the spec's \`kind\`), and the renderers each allows. */
export const PANEL_KINDS = {
${entries.join('\n')}
} as const;

export type PanelKind = keyof typeof PANEL_KINDS;
`;
}

const cell = (s: string) => s.replace(/\|/g, '\\|');
const link = (id: string) => `[${id}](lld/${id}.md)`;
const code = (xs: string[]) => (xs.length ? xs.map((x) => `\`${x}\``).join(', ') : '—');

function buildTaxonomyBlock(items: Item[]): string {
  const all = sorted(items);
  const out: string[] = [];
  const count = (pred: (i: Item) => boolean) => all.filter(pred).length;

  out.push(
    `**${all.length} items:** ${count((i) => i.status === 'stable')} stable, ${count((i) => i.status === 'beta')} beta (built, no LLD or story yet), ${count((i) => i.status === 'proposed')} proposed (gaps), ${count((i) => i.status === 'deprecated')} deprecated.`,
    '',
  );

  out.push('### Ladder map', '');
  out.push(
    'Rows are the UI ladder (Frost), columns the BI ladder (SQLBI). Proposed items are in _italics_.',
    '',
  );
  const cols = [...BI_LEVELS, null] as const;
  out.push(`| UI ↓ / BI → | ${cols.map((c) => c ?? 'UI only').join(' | ')} |`);
  out.push(`| --- | ${cols.map(() => '---').join(' | ')} |`);
  for (const level of ATOMIC_LEVELS) {
    const cells = cols.map((col) =>
      all
        .filter((i) => i.atomicLevel === level && i.biLevel === col)
        .map((i) => (i.status === 'proposed' ? `_${link(i.id)}_` : link(i.id)))
        .join(', '),
    );
    out.push(`| **${level}s** | ${cells.map((c) => c || ' ').join(' | ')} |`);
  }
  out.push('');

  for (const level of ATOMIC_LEVELS) {
    out.push(`### ${level[0]!.toUpperCase()}${level.slice(1)}s`, '');
    out.push('| Item | What it is | BI level | Status | Engine | Composes | Implemented in |');
    out.push('| --- | --- | --- | --- | --- | --- | --- |');
    for (const i of all.filter((x) => x.atomicLevel === level))
      out.push(
        `| ${link(i.id)} ${cell(i.name)} | ${cell(i.summary)} | ${i.biLevel ?? '—'} | ${i.status} | ${i.renderEngine} | ${i.composes.length ? i.composes.map(link).join(', ') : '—'} | ${code(i.source)} |`,
      );
    out.push('');
  }

  out.push('### Panel kinds', '');
  out.push(
    'A dashboard panel names its organism in `kind`. The schema enum is generated from this table, and the renderer must be one the kind allows.',
    '',
  );
  out.push('| `kind` | Organism | Allowed `renderer` | Status |');
  out.push('| --- | --- | --- | --- |');
  for (const i of all.filter((x) => x.panel))
    out.push(
      `| ${i.status === 'proposed' ? '(not yet)' : `\`${i.id}\``} | ${link(i.id)} | ${code(i.panel!.renderers)} | ${i.status} |`,
    );
  out.push('');

  out.push('### Gap list', '');
  out.push('Proposed items: each needs an LLD (Phase 4) before it is built.', '');
  out.push('| Priority | Item | Level | Why it is needed |');
  out.push('| --- | --- | --- | --- |');
  for (const p of GAP_PRIORITIES)
    for (const i of all.filter((x) => x.gap?.priority === p))
      out.push(`| ${p} | ${link(i.id)} | ${i.atomicLevel} | ${cell(i.gap!.reason)} |`);

  return out.join('\n');
}

/* -------------------------------------------------------------------- run */

async function main() {
  const check = process.argv.includes('--check');
  const { items, errors } = loadItems();
  if (errors.length) {
    for (const e of errors) console.error(`✗ ${e}`);
    console.error(`✗ catalog: ${errors.length} problem(s) in docs/lld front matter`);
    process.exit(1);
  }

  const taxonomyPath = join(ROOT, TAXONOMY);
  const taxonomy = readFileSync(taxonomyPath, 'utf8');
  const [before, rest] = taxonomy.split(BEGIN);
  const after = rest?.split(END)[1];
  if (before === undefined || after === undefined) {
    console.error(`✗ catalog: ${TAXONOMY} needs the markers\n  ${BEGIN}\n  ${END}`);
    process.exit(1);
  }

  const files: Record<string, string> = {
    'catalog.json': buildCatalogJson(items),
    'src/spec/generated/panel-kinds.ts': buildPanelKindsTs(items),
    [TAXONOMY]: `${before}${BEGIN}\n\n${buildTaxonomyBlock(items)}\n\n${END}${after}`,
  };
  const stale: string[] = [];
  for (const [name, raw] of Object.entries(files)) {
    const path = join(ROOT, name);
    const options = (await resolveConfig(path)) ?? {};
    const text = await format(raw, { ...options, filepath: path });
    if ((existsSync(path) ? readFileSync(path, 'utf8') : undefined) === text) continue;
    if (check) stale.push(name);
    else {
      mkdirSync(dirname(path), { recursive: true });
      writeFileSync(path, text);
    }
  }
  if (check && stale.length) {
    console.error(`✗ catalog: stale generated files: ${stale.join(', ')}`);
    console.error('  run `npm run catalog:build` and commit the result');
    process.exit(1);
  }
  const kinds = panelKinds(items).map((i) => i.id);
  console.log(
    `✓ catalog: ${items.length} items, panel kinds ${kinds.join(', ')}; ${check ? 'generated files are up to date' : 'wrote catalog.json, panel-kinds.ts, taxonomy tables'}`,
  );
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) void main();

/**
 * Token build: tokens/**.tokens.json (DTCG) + tokens/format.json → src/theme/generated/*.
 *
 *   npm run tokens:build            # write outputs
 *   npm run tokens:build -- --check # fail if any output is stale (used by verify)
 *
 * Outputs (all write-protected by .claude/hooks/guard-paths.mjs):
 *   tokens.css            CSS custom properties: :root, [data-theme], [data-density],
 *                         prefers-color-scheme / prefers-contrast / prefers-reduced-motion,
 *                         plus shadcn variable aliases
 *   themes.ts             typed resolved values per theme and density, and formats
 *   engines.ts            Vega-Lite config, Flint theme and Plotly theme per theme
 *   figma-variables.json  collections (Primitives, Data viz, Semantic, Density, Component)
 *                         with modes and aliases, for a future Figma sync (ADR-001)
 *   public/favicon.svg    the brand mark in the light theme's accent colours
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { format, resolveConfig } from 'prettier';
import { flintTheme, lookup, plotlyTheme, vegaLiteConfig } from './engines';
import {
  DENSITIES,
  ROOT,
  THEMES,
  cssVar,
  loadFormats,
  nest,
  resolveAll,
  type Resolved,
  type ResolvedSet,
  type Token,
  type Typography,
} from './lib';
import { validate } from './validate';

const OUT = join(ROOT, 'src/theme/generated');
const HEADER =
  'Generated by scripts/tokens/build.ts from tokens/. Do not edit; run `npm run tokens:build`.';
const EMITTED_TIERS = new Set(['semantic', 'component', 'density', 'motion']);

const sets = resolveAll();
const formats = loadFormats();
const setOf = (theme: string, density: string) =>
  sets.find((s) => s.theme === theme && s.density === density)!;
const base = setOf('light', 'comfortable');

/* --------------------------------------------------------------------- CSS */

const isTypography = (v: Resolved): v is Typography =>
  typeof v === 'object' && !Array.isArray(v) && 'fontSize' in v;

function cssDecls(t: Token, v: Resolved): string[] {
  const name = cssVar(t.path);
  if (isTypography(v))
    return [
      `${name}-font: ${v.fontWeight} ${v.fontSize}px/${v.lineHeight} ${v.fontFamily};`,
      `${name}-letter-spacing: ${v.letterSpacing}px;`,
    ];
  switch (t.type) {
    case 'dimension':
      return [`${name}: ${v}px;`];
    case 'duration':
      return [`${name}: ${v}ms;`];
    case 'cubicBezier':
      return [`${name}: cubic-bezier(${(v as number[]).join(', ')});`];
    default:
      return [`${name}: ${v};`];
  }
}

type Variation = 'none' | 'theme' | 'density';
function variation(path: string): Variation {
  const key = (s: ResolvedSet) => JSON.stringify(s.tokens.get(path)!.resolved);
  const byTheme = new Set(THEMES.map((t) => key(setOf(t, 'comfortable'))));
  const byDensity = new Set(DENSITIES.map((d) => key(setOf('light', d))));
  if (byTheme.size > 1 && byDensity.size > 1)
    throw new Error(`${path} varies by both theme and density; split it into two tokens`);
  return byTheme.size > 1 ? 'theme' : byDensity.size > 1 ? 'density' : 'none';
}

function buildCss(): string {
  const emitted = [...base.tokens.values()].filter((t) => EMITTED_TIERS.has(t.tier));
  const groups: Record<Variation, Token[]> = { none: [], theme: [], density: [] };
  for (const t of emitted) groups[variation(t.path)].push(t);
  const block = (selector: string, set: ResolvedSet, tokens: Token[], extra: string[] = []) =>
    `${selector} {\n${[...extra, ...tokens.flatMap((t) => cssDecls(t, set.tokens.get(t.path)!.resolved))].map((l) => `  ${l}`).join('\n')}\n}`;
  const scheme = (theme: string) => [`color-scheme: ${theme === 'dark' ? 'dark' : 'light'};`];
  const durations = groups.none.filter((t) => t.type === 'duration');
  const alias = (name: string, path: string) => {
    if (!base.tokens.has(path)) throw new Error(`shadcn alias ${name} → unknown ${path}`);
    return `${name}: var(${cssVar(path)});`;
  };
  return [
    `/* ${HEADER} */`,
    block(':root', base, groups.none),
    block(
      ":root,\n[data-theme='light']",
      setOf('light', 'comfortable'),
      groups.theme,
      scheme('light'),
    ),
    ...THEMES.filter((t) => t !== 'light').map((t) =>
      block(`[data-theme='${t}']`, setOf(t, 'comfortable'), groups.theme, scheme(t)),
    ),
    `@media (prefers-color-scheme: dark) {\n${block(':root:not([data-theme])', setOf('dark', 'comfortable'), groups.theme, scheme('dark'))}\n}`,
    `@media (prefers-contrast: more) {\n${block(':root:not([data-theme])', setOf('hc', 'comfortable'), groups.theme, scheme('hc'))}\n}`,
    block(":root,\n[data-density='comfortable']", setOf('light', 'comfortable'), groups.density),
    ...DENSITIES.filter((d) => d !== 'comfortable').map((d) =>
      block(`[data-density='${d}']`, setOf('light', d), groups.density),
    ),
    `@media (prefers-reduced-motion: reduce) {\n  :root {\n${durations.map((t) => `    ${cssVar(t.path)}: 0ms;`).join('\n')}\n  }\n}`,
    `/* shadcn/ui variable aliases, so copied-in components follow the semantic tier. */\n:root {\n${[
      alias('--background', 'color.bg.canvas'),
      alias('--foreground', 'color.text.primary'),
      alias('--card', 'color.bg.surface'),
      alias('--card-foreground', 'color.text.primary'),
      alias('--popover', 'color.bg.surface-raised'),
      alias('--popover-foreground', 'color.text.primary'),
      alias('--primary', 'color.bg.accent'),
      alias('--primary-foreground', 'color.text.on-accent'),
      alias('--muted-foreground', 'color.text.muted'),
      alias('--destructive', 'color.status.danger'),
      alias('--border', 'color.border.subtle'),
      alias('--input', 'color.border.control'),
      alias('--ring', 'color.focus.ring'),
      alias('--radius', 'radius.panel'),
      ...[1, 2, 3, 4, 5].map((i) => alias(`--chart-${i}`, `color.data.categorical.${i}`)),
    ]
      .map((l) => `  ${l}`)
      .join('\n')}\n}`,
    '',
  ].join('\n\n');
}

/* ------------------------------------------------------------- themes.ts */

const isIdent = (k: string) => /^[A-Za-z_$][\w$]*$/.test(k);
const key = (k: string) => (isIdent(k) ? k : JSON.stringify(k));

function tsType(v: unknown, indent = ''): string {
  if (typeof v === 'string') return 'string';
  if (typeof v === 'number') return 'number';
  if (Array.isArray(v)) return 'readonly number[]';
  const obj = v as Record<string, unknown>;
  if ('fontSize' in obj && 'lineHeight' in obj) return 'Typography';
  const inner = indent + '  ';
  return `{\n${Object.entries(obj)
    .map(([k, val]) => `${inner}readonly ${key(k)}: ${tsType(val, inner)};`)
    .join('\n')}\n${indent}}`;
}

function treeOf(set: ResolvedSet, include: (t: Token) => boolean) {
  return nest(
    [...set.tokens.values()].filter(include).map((t) => [t.path, t.resolved] as [string, unknown]),
  );
}
const themeTokens = (t: Token) => EMITTED_TIERS.has(t.tier) && t.tier !== 'density';
const densityTokens = (t: Token) => t.tier === 'density';

function buildThemesTs(): string {
  const themeTree = treeOf(base, themeTokens);
  const densityTree = treeOf(base, densityTokens);
  const themes = Object.fromEntries(
    THEMES.map((t) => [t, treeOf(setOf(t, 'comfortable'), themeTokens)]),
  );
  const densities = Object.fromEntries(
    DENSITIES.map((d) => [d, treeOf(setOf('light', d), densityTokens)]),
  );
  return `/* ${HEADER} */

export const THEMES = ${JSON.stringify(THEMES)} as const;
export const DENSITIES = ${JSON.stringify(DENSITIES)} as const;
export type ThemeName = (typeof THEMES)[number];
export type DensityName = (typeof DENSITIES)[number];

export interface Typography {
  readonly fontFamily: string;
  readonly fontSize: number;
  readonly fontWeight: number;
  readonly letterSpacing: number;
  readonly lineHeight: number;
}

/** Semantic, component and motion tokens, resolved. Dimensions in px, durations in ms. */
export type ResolvedTheme = ${tsType(themeTree)};

/** Spacing for one density. */
export type ResolvedDensity = ${tsType(densityTree)};

export const themes: Record<ThemeName, ResolvedTheme> = ${JSON.stringify(themes)};

export const densities: Record<DensityName, ResolvedDensity> = ${JSON.stringify(densities)};

/** d3-format and d3-time-format specifiers (tokens/format.json). */
export const formats = ${JSON.stringify(formats)} as const;
`;
}

/* ------------------------------------------------------------ engines.ts */

function buildEnginesTs(): string {
  const per = <T>(f: (set: ResolvedSet) => T) =>
    JSON.stringify(Object.fromEntries(THEMES.map((t) => [t, f(setOf(t, 'comfortable'))])));
  return `/* ${HEADER} */
import type { ThemeSpec } from 'flint-chart';
import type { Layout } from 'plotly.js';
import type { Config } from 'vega-lite';
import type { ThemeName } from './themes';

export interface PlotlyTheme {
  layout: Partial<Layout>;
  colorway: string[];
  marker: { size: number; opacity: number };
  marginTopWithLegend: number;
}

export const vegaLiteConfig: Record<ThemeName, Config> = ${per((s) => vegaLiteConfig(lookup(s), formats))};

export const flintTheme: Record<ThemeName, ThemeSpec> = ${per((s) => flintTheme(lookup(s), s.theme))};

export const plotlyTheme: Record<ThemeName, PlotlyTheme> = ${per((s) => plotlyTheme(lookup(s), formats))};
`;
}

/* ------------------------------------------------------- Figma variables */

function buildFigma(): string {
  const figmaName = (path: string) => path.replace(/\./g, '/');
  const value = (t: Token, v: Resolved): unknown => {
    if (t.type === 'color') {
      const hex = String(v);
      const n = (i: number) =>
        Math.round((parseInt(hex.slice(i, i + 2), 16) / 255) * 10000) / 10000;
      return { r: n(1), g: n(3), b: n(5), a: 1 };
    }
    if (typeof v === 'number' || typeof v === 'string') return v;
    return JSON.stringify(v);
  };
  const figmaType = (t: Token) =>
    t.type === 'color' ? 'COLOR' : t.type === 'fontFamily' ? 'STRING' : 'FLOAT';
  const entry = (t: Token, modes: [string, ResolvedSet][]) => ({
    name: figmaName(t.path),
    type: figmaType(t),
    ...(t.description ? { description: t.description } : {}),
    valuesByMode: Object.fromEntries(
      modes.map(([mode, set]) => {
        const tok = set.tokens.get(t.path)!;
        const direct = typeof tok.value === 'string' && /^\{.+\}$/.test(tok.value);
        return [
          mode,
          direct
            ? { type: 'VARIABLE_ALIAS', name: figmaName(tok.refs[0]!) }
            : value(tok, tok.resolved),
        ];
      }),
    ),
  });
  // Figma variables have no composite type: typography becomes text styles in a later sync.
  const all = [...base.tokens.values()].filter(
    (t) => t.type !== 'typography' && t.type !== 'cubicBezier',
  );
  const single: [string, ResolvedSet][] = [['Value', base]];
  const collection = (
    name: string,
    tiers: string[],
    modes: [string, ResolvedSet][],
    filter = (_t: Token) => true,
  ) => ({
    name,
    modes: modes.map(([m]) => m),
    variables: all.filter((t) => tiers.includes(t.tier) && filter(t)).map((t) => entry(t, modes)),
  });
  const themeModes = THEMES.map((t) => [t, setOf(t, 'comfortable')] as [string, ResolvedSet]);
  const densityModes = DENSITIES.map((d) => [d, setOf('light', d)] as [string, ResolvedSet]);
  return JSON.stringify(
    {
      $description: `${HEADER} Intermediate payload for a Figma Variables sync (ADR-001: code is the source, Figma mirrors it). Aliases name the target variable by path.`,
      collections: [
        collection('Primitives', ['primitive', 'motion'], single),
        collection('Data viz', ['dataviz'], single),
        collection('Semantic', ['semantic'], themeModes, (t) => variation(t.path) === 'theme'),
        collection(
          'Semantic (all modes)',
          ['semantic'],
          single,
          (t) => variation(t.path) !== 'theme',
        ),
        collection('Density', ['density'], densityModes),
        collection('Component', ['component'], single),
      ],
    },
    null,
    2,
  );
}

/* ---------------------------------------------------------------- favicon */

function buildFavicon(): string {
  const set = setOf('light', 'comfortable');
  const color = (p: string) => String(set.tokens.get(p)!.resolved);
  // Icon geometry (a 32px tile with three rising bars) is artwork, not a token.
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><!-- ${HEADER} --><rect width="32" height="32" rx="7" fill="${color('color.bg.accent')}"/><g fill="${color('color.text.on-accent')}"><rect x="7" y="17" width="4" height="8" rx="1"/><rect x="14" y="11" width="4" height="14" rx="1"/><rect x="21" y="7" width="4" height="18" rx="1"/></g></svg>\n`;
}

/* -------------------------------------------------------------------- run */

async function main() {
  const check = process.argv.includes('--check');
  const { findings } = validate(sets);
  const errors = findings.filter((f) => f.level === 'error');
  if (errors.length) {
    for (const e of errors) console.error(`✗ [${e.rule}] ${e.message}`);
    console.error(
      '✗ tokens:build refused: fix the validation errors first (npm run tokens:validate)',
    );
    process.exit(1);
  }

  const files: Record<string, string> = {
    'src/theme/generated/tokens.css': buildCss(),
    'src/theme/generated/themes.ts': buildThemesTs(),
    'src/theme/generated/engines.ts': buildEnginesTs(),
    'src/theme/generated/figma-variables.json': buildFigma(),
    'public/favicon.svg': buildFavicon(),
  };
  mkdirSync(OUT, { recursive: true });
  const stale: string[] = [];
  for (const [name, raw] of Object.entries(files)) {
    const path = join(ROOT, name);
    const options = (await resolveConfig(path)) ?? {};
    const text = name.endsWith('.svg') ? raw : await format(raw, { ...options, filepath: path });
    const current = existsSync(path) ? readFileSync(path, 'utf8') : undefined;
    if (current === text) continue;
    if (check) stale.push(name);
    else writeFileSync(path, text);
  }
  if (check && stale.length) {
    console.error(`✗ tokens: stale generated files: ${stale.join(', ')}`);
    console.error('  run `npm run tokens:build` and commit the result');
    process.exit(1);
  }
  console.log(
    `✓ tokens: ${check ? 'generated files are up to date' : `wrote ${Object.keys(files).length} generated files`}`,
  );
}

void main();

/**
 * Phase 0 palette audit of src/theme/tokens.ts: WCAG 2.2 contrast for text and graphical objects,
 * and colour-vision-deficiency separability of the categorical palette (Machado et al. 2009,
 * severity 1.0; distance = CIEDE2000). Seed for the Phase 1 `tokens:validate` script.
 *
 *   npx tsx scripts/inventory/palette-audit.ts   # writes docs/inventory/palette-audit.md
 */
import { writeFileSync } from 'node:fs';
import { tokens } from '../../src/theme/tokens';

type RGB = [number, number, number];
const hex = (h: string): RGB => {
  const s = h.replace('#', '');
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16) / 255) as RGB;
};
const lin = (c: number) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const unlin = (c: number) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const luminance = (h: string) => {
  const [r, g, b] = hex(h).map(lin) as RGB;
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
export const contrast = (a: string, b: string) => {
  const [x, y] = [luminance(a), luminance(b)].sort((m, n) => n - m) as [number, number];
  return (x + 0.05) / (y + 0.05);
};

/* Machado 2009, severity 1.0, applied in linear RGB. */
const MACHADO = {
  protanopia: [
    [0.152286, 1.052583, -0.204868],
    [0.114503, 0.786281, 0.099216],
    [-0.003882, -0.048116, 1.051998],
  ],
  deuteranopia: [
    [0.367322, 0.860646, -0.227968],
    [0.280085, 0.672501, 0.047413],
    [-0.01182, 0.04294, 0.968881],
  ],
} as const;
const simulate = (h: string, m: readonly (readonly number[])[]): RGB => {
  const v = hex(h).map(lin);
  return m.map((row) =>
    unlin(Math.min(1, Math.max(0, row[0]! * v[0]! + row[1]! * v[1]! + row[2]! * v[2]!))),
  ) as RGB;
};

const toLab = ([r, g, b]: RGB): RGB => {
  const [R, G, B] = [r, g, b].map(lin) as RGB;
  const f = (t: number) => (t > 216 / 24389 ? Math.cbrt(t) : ((24389 / 27) * t + 16) / 116);
  const X = f((0.4124 * R + 0.3576 * G + 0.1805 * B) / 0.95047);
  const Y = f(0.2126 * R + 0.7152 * G + 0.0722 * B);
  const Z = f((0.0193 * R + 0.1192 * G + 0.9505 * B) / 1.08883);
  return [116 * Y - 16, 500 * (X - Y), 200 * (Y - Z)];
};

/** CIEDE2000 (Sharma, Wu & Dalal 2005). */
export function deltaE2000([L1, a1, b1]: RGB, [L2, a2, b2]: RGB): number {
  const rad = Math.PI / 180;
  const C1 = Math.hypot(a1, b1);
  const C2 = Math.hypot(a2, b2);
  const Cb = (C1 + C2) / 2;
  const G = 0.5 * (1 - Math.sqrt(Cb ** 7 / (Cb ** 7 + 25 ** 7)));
  const [ap1, ap2] = [(1 + G) * a1, (1 + G) * a2];
  const [Cp1, Cp2] = [Math.hypot(ap1, b1), Math.hypot(ap2, b2)];
  const hp = (b: number, a: number) => {
    const h = Math.atan2(b, a) / rad;
    return h < 0 ? h + 360 : h;
  };
  const [hp1, hp2] = [hp(b1, ap1), hp(b2, ap2)];
  const dL = L2 - L1;
  const dC = Cp2 - Cp1;
  let dh = hp2 - hp1;
  if (Cp1 * Cp2 === 0) dh = 0;
  else if (dh > 180) dh -= 360;
  else if (dh < -180) dh += 360;
  const dH = 2 * Math.sqrt(Cp1 * Cp2) * Math.sin((dh / 2) * rad);
  const Lb = (L1 + L2) / 2;
  const Cpb = (Cp1 + Cp2) / 2;
  let hb = hp1 + hp2;
  if (Cp1 * Cp2 !== 0)
    hb = Math.abs(hp1 - hp2) > 180 ? (hp1 + hp2 + (hp1 + hp2 < 360 ? 360 : -360)) / 2 : hb / 2;
  const T =
    1 -
    0.17 * Math.cos((hb - 30) * rad) +
    0.24 * Math.cos(2 * hb * rad) +
    0.32 * Math.cos((3 * hb + 6) * rad) -
    0.2 * Math.cos((4 * hb - 63) * rad);
  const SL = 1 + (0.015 * (Lb - 50) ** 2) / Math.sqrt(20 + (Lb - 50) ** 2);
  const SC = 1 + 0.045 * Cpb;
  const SH = 1 + 0.015 * Cpb * T;
  const RT =
    -2 *
    Math.sqrt(Cpb ** 7 / (Cpb ** 7 + 25 ** 7)) *
    Math.sin(60 * Math.exp(-(((hb - 275) / 25) ** 2)) * rad);
  return Math.sqrt((dL / SL) ** 2 + (dC / SC) ** 2 + (dH / SH) ** 2 + RT * (dC / SC) * (dH / SH));
}

/* ---------------------------------------------------------------- report */

const out: string[] = [
  '# Palette audit (generated)',
  '',
  'Generated by `scripts/inventory/palette-audit.ts` from `src/theme/tokens.ts`. Do not edit.',
  '',
  '## Text and UI contrast (WCAG 2.2: text ≥ 4.5, large text ≥ 3, graphical objects ≥ 3)',
  '',
  '| Foreground | Background | Ratio | Needs | Result |',
  '| --- | --- | --- | --- | --- |',
];
const c = tokens.color;
const pairs: [string, string, string, string, number][] = [
  ['text', c.text, 'surface', c.surface, 4.5],
  ['text', c.text, 'background', c.background, 4.5],
  ['textMuted', c.textMuted, 'surface', c.surface, 4.5],
  ['textMuted', c.textMuted, 'background', c.background, 4.5],
  ['accent', c.accent, 'surface', c.surface, 3],
  ['#fff (chip on)', '#ffffff', 'accent', c.accent, 4.5],
  ['#b42318 (error)', '#b42318', 'surface', c.surface, 4.5],
  ['border', c.border, 'surface', c.surface, 3],
  ['grid', c.grid, 'surface', c.surface, 1],
];
for (const [fn, f, bn, b, need] of pairs) {
  const r = contrast(f, b);
  out.push(
    `| ${fn} \`${f}\` | ${bn} \`${b}\` | ${r.toFixed(2)} | ${need} | ${r >= need ? 'pass' : '**fail**'} |`,
  );
}
out.push(
  '',
  '`border` is decorative (panel edge) and `grid` is a non-essential reference line, so failures there are informational; `border` becomes essential if it is the only boundary of an input (chips, select).',
  '',
  '## Categorical series vs surface (graphical objects ≥ 3:1)',
  '',
  '| # | Colour | vs surface | Result |',
  '| --- | --- | --- | --- |',
);
tokens.categorical.forEach((col, i) => {
  const r = contrast(col, c.surface);
  out.push(`| ${i + 1} | \`${col}\` | ${r.toFixed(2)} | ${r >= 3 ? 'pass' : '**fail**'} |`);
});

out.push(
  '',
  '## Categorical separability (CIEDE2000, closest pairs)',
  '',
  'ΔE₀₀ < 10: hard to tell apart in small marks (lines, points); < 5: confusable. Thresholds are provisional; Phase 1 fixes them in ADR-001.',
  '',
  '| Vision | Closest pair | ΔE₀₀ | Pairs < 10 |',
  '| --- | --- | --- | --- |',
);
const cat = tokens.categorical;
const visions: [string, (h: string) => RGB][] = [
  ['normal', hex],
  ['deuteranopia', (h) => simulate(h, MACHADO.deuteranopia)],
  ['protanopia', (h) => simulate(h, MACHADO.protanopia)],
];
for (const [name, sim] of visions) {
  const labs = cat.map((h) => toLab(sim(h)));
  const ds: [number, number, number][] = [];
  for (let i = 0; i < cat.length; i++)
    for (let j = i + 1; j < cat.length; j++) ds.push([i, j, deltaE2000(labs[i]!, labs[j]!)]);
  ds.sort((a, b) => a[2] - b[2]);
  const [i, j, d] = ds[0]!;
  const close = ds
    .filter((x) => x[2] < 10)
    .map(([a, b, e]) => `${a + 1}–${b + 1} (${e.toFixed(1)})`);
  out.push(
    `| ${name} | ${i + 1} \`${cat[i]}\` – ${j + 1} \`${cat[j]}\` | ${d.toFixed(1)} | ${close.join(', ') || 'none'} |`,
  );
}

out.push(
  '',
  '## Sequential ramp',
  '',
  '| Stop | Colour | L* | vs surface |',
  '| --- | --- | --- | --- |',
);
tokens.sequential.forEach((col, i) =>
  out.push(
    `| ${i + 1} | \`${col}\` | ${toLab(hex(col))[0].toFixed(1)} | ${contrast(col, c.surface).toFixed(2)} |`,
  ),
);
out.push(
  '',
  'A sequential ramp should rise monotonically in lightness (L*) with roughly even steps; stop 1 at ~1.1:1 against the surface disappears on white cells.',
  '',
);

writeFileSync('docs/inventory/palette-audit.md', out.join('\n'));

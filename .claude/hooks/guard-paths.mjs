// PreToolUse (Edit|MultiEdit|Write): block edits to generated or vendored files and point Claude
// at the source of truth instead.
import { existsSync, readFileSync } from 'node:fs';
import { block, readInput, rel, run } from './lib.mjs';

const RULES = [
  [/^node_modules\//, 'node_modules is managed by npm.'],
  [/^dist\//, 'dist/ is build output; run `npm run build`.'],
  [/^package-lock\.json$/, 'package-lock.json is managed by npm; run `npm install <pkg>`.'],
  [
    /^dashboards\/dashboard\.schema\.json$/,
    'Generated from src/spec/schema.ts; edit the Zod schema then run `npm run spec:schema`.',
  ],
  [
    /^public\/data\//,
    'Fixtures are generated; edit scripts/generate-fixtures.ts then run `npm run data:fixtures`.',
  ],
  [
    /-snapshots\//,
    'Screenshot baselines change only via `npm run test:e2e -- --update-snapshots` after a reviewed visual change.',
  ],
  [
    /^src\/theme\/generated\//,
    'Generated from tokens/; edit the DTCG source in tokens/ then run `npm run tokens:build`.',
  ],
  [
    /^public\/favicon\.svg$/,
    'Generated from the brand tokens by `npm run tokens:build`; edit tokens/ instead.',
  ],
  [
    /^docs\/tokens\/contrast-matrix\.md$/,
    'Generated by `npm run tokens:validate`; change tokens/ or the thresholds in ADR-001.',
  ],
  [/^\.env/, 'Never write secrets files.'],
];

const input = await readInput();
const file = input.tool_input?.file_path;
if (!file) process.exit(0);
const path = rel(file);

// learn-taste: Do's and Don'ts changes only through `npm run design:taste` on a taste/* branch,
// reviewed as a PR. Never a silent edit.
if (path === 'DESIGN.md') {
  const section = (text) => /## Do's and Don'ts\n([\s\S]*?)(?=\n## |$)/.exec(text ?? '')?.[1] ?? '';
  const current = existsSync(file) ? readFileSync(file, 'utf8') : '';
  const ti = input.tool_input ?? {};
  const touches =
    input.tool_name === 'Write'
      ? section(ti.content) !== section(current)
      : [ti.old_string, ...(ti.edits ?? []).map((e) => e.old_string)]
          .filter(Boolean)
          .some((old) => section(current).includes(old) || old.includes("## Do's and Don'ts"));
  const branch = run('git', ['branch', '--show-current']).output;
  if (touches && !branch.startsWith('taste/'))
    block(
      "Blocked edit to DESIGN.md › Do's and Don'ts: rules change only through review. Use " +
        '`npm run design:taste -- "Do …"` (creates a taste/* branch and commit) and open a PR.',
    );
}
for (const [pattern, reason] of RULES)
  if (pattern.test(path)) block(`Blocked edit to ${path}: ${reason}`);
